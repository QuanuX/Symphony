type object = map[string]any

func die(e error) {
	if e != nil {
		fmt.Fprintln(os.Stderr, e)
		os.Exit(1)
	}
}
func encoded(v any) []byte { b, e := json.MarshalIndent(v, "", "  "); die(e); return append(b, '\n') }
func shape(t reflect.Type) object {
	switch t.Kind() {
	case reflect.Pointer:
		return object{"oneOf": []any{object{"type": "null"}, shape(t.Elem())}}
	case reflect.Slice:
		return object{"type": "array", "items": shape(t.Elem())}
	case reflect.String:
		return object{"type": "string"}
	case reflect.Bool:
		return object{"type": "boolean"}
	case reflect.Struct:
		return object{"$ref": "#/$defs/" + t.Name()}
	default:
		panic("unsupported owner field " + t.String())
	}
}
func declaration(t reflect.Type, protocols map[string]string) object {
	properties := object{}
	required := []string{}
	for i := 0; i < t.NumField(); i++ {
		field := t.Field(i)
		name := field.Tag.Get("json")
		required = append(required, name)
		spec := shape(field.Type)
		if field.Type.Kind() == reflect.String {
			switch {
			case strings.HasSuffix(name, "digest") || name == "qualification_ref":
				spec["pattern"] = "^sha256:[0-9a-f]{64}$"
			case name == "generation" || name == "profile_generation" || name == "uid" || name == "gid" || name == "port" || name == "control_bytes" || name == "captured_bytes" || name == "cleanup_seconds":
				spec["pattern"] = "^[1-9][0-9]*$"
			case name == "host_id" || name == "tops_id" || name == "profile_id" || name == "package_id":
				spec["pattern"] = "^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$"
			case name == "request_id" || name == "operation_id":
				spec["pattern"] = "^[0-9a-f]{8}-[0-9a-f]{4}-[47][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$"
			}
		}
		properties[name] = spec
	}
	if protocol, ok := protocols[t.Name()]; ok {
		properties["protocol"] = object{"const": protocol}
	}
	return object{"type": "object", "additionalProperties": false, "properties": properties, "required": required}
}
func main() {
	check := flag.Bool("check", false, "check projections without writing")
	rootFlag := flag.String("repo", "../..", "repository root")
	flag.Parse()
	root, e := filepath.Abs(*rootFlag)
	die(e)
	owner := filepath.Join(root, "tools/sov-transport-profile-admin/contract")
	if _, e = os.Stat(filepath.Join(owner, "types.go")); e != nil {
		die(fmt.Errorf("run from the profile module root or select --repo"))
	}
	protocols := map[string]string{"Profile": c.ProfileProtocol, "Policy": c.PolicyProtocol, "Snapshot": c.SnapshotProtocol, "Plan": c.PlanProtocol, "Request": c.RequestProtocol, "Result": c.ResultProtocol, "PackageManifest": c.PackageProtocol}
	definitions := object{}
	for _, value := range []any{c.Scope{}, c.Principal{}, c.PackageRef{}, c.EndpointConstraint{}, c.Limits{}, c.Configuration{}, c.PolicyRef{}, c.Profile{}, c.Policy{}, c.Snapshot{}, c.Expected{}, c.Change{}, c.Plan{}, c.Recovery{}, c.Request{}, c.Attempt{}, c.Result{}, c.PackageFile{}, c.PackageManifest{}} {
		t := reflect.TypeOf(value)
		definitions[t.Name()] = declaration(t, protocols)
	}
	enum := func(owner, field string, values []string) {
		definitions[owner].(object)["properties"].(object)[field] = object{"enum": values}
	}
	enum("Request", "operation", []string{"list", "inspect", "plan", "apply", "status", "recover"})
	enum("Change", "action", []string{"create", "replace", "enable", "disable", "remove", "policy"})
	enum("Recovery", "action", []string{"complete", "abort"})
	enum("Profile", "state", []string{"enabled", "disabled", "removed"})
	variants := []any{}
	for _, name := range []string{"Request", "Result", "Plan", "Snapshot", "Profile", "Policy", "PackageManifest"} {
		variants = append(variants, object{"$ref": "#/$defs/" + name})
	}
	schema := encoded(object{"$schema": "https://json-schema.org/draft/2020-12/schema", "$id": "symphony.sov.transport-profile.schemas.v1", "$comment": "Generated closed wire shapes. Contract validators additionally enforce state, digest, generation, package and authority bindings.", "$defs": definitions, "oneOf": variants})
	outputs := map[string][]byte{"knowledge/sov/transport-profiles/schemas.json": schema}
	generated, e := format.Source([]byte("// Code generated by scripts/generate_contract.go; DO NOT EDIT.\npackage contract\n\nconst SchemaJSON = `" + string(schema) + "`\n"))
	die(e)
	outputs["tools/sov-transport-profile-admin/contract/schema_generated.go"] = generated
	entries, e := os.ReadDir(owner)
	die(e)
	for _, entry := range entries {
		name := entry.Name()
		if entry.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") || name == "schema_generated.go" {
			continue
		}
		source, e := os.ReadFile(filepath.Join(owner, name))
		die(e)
		mirror, e := format.Source([]byte("// Code generated from sov-transport-profile-admin/contract; DO NOT EDIT.\n" + strings.Replace(string(source), "package contract", "package wire", 1)))
		die(e)
		outputs["tools/qxctl/internal/transportprofile/wire/"+strings.TrimSuffix(name, ".go")+"_generated.go"] = mirror
	}
	outputs["tools/qxctl/internal/transportprofile/wire/schema_generated.go"] = []byte(strings.Replace(string(generated), "package contract", "package wire", 1))
	for _, name := range []string{"contract.go", "contract_test.go"} {
		raw, e := os.ReadFile(filepath.Join(root, "tools/sov-transport-profile-admin/internal/transportaudit", name))
		die(e)
		outputs["modules/secure-identity-access-governance/internal/transportaudit/"+name] = raw
	}
	request := declaration(reflect.TypeOf(a.Request{}), map[string]string{"Request": a.Protocol})
	request["$schema"] = "https://json-schema.org/draft/2020-12/schema"
	request["$id"] = "symphony.ssiag.transport-profile-audit-request.v1"
	properties := request["properties"].(object)
	properties["observed_digest"] = object{"type": "string", "pattern": "^(sha256:[0-9a-f]{64})?$"}
	properties["phase"] = object{"enum": []string{"intent", "outcome"}}
	properties["resolution"] = object{"enum": []string{"pending", "published", "aborted"}}
	properties["action"] = object{"enum": []string{"create", "replace", "enable", "disable", "remove", "policy"}}
	response := object{"$schema": "https://json-schema.org/draft/2020-12/schema", "$id": "symphony.ssiag.transport-profile-audit-response.v1", "type": "object", "additionalProperties": false, "required": []string{"protocol", "request_digest", "receipt"}, "properties": object{"protocol": object{"const": a.Protocol}, "request_digest": object{"type": "string", "pattern": "^sha256:[0-9a-f]{64}$"}, "receipt": object{"$ref": "../../../stav/schemas/v1/receipt.schema.json"}}}
	outputs["knowledge/ssiag/schemas/v1/transport-profile-audit-request.schema.json"] = encoded(request)
	outputs["knowledge/ssiag/schemas/v1/transport-profile-audit-response.schema.json"] = encoded(response)
	paths := []string{}
	for path := range outputs {
		paths = append(paths, path)
	}
	sort.Strings(paths)
	stale := []string{}
	for _, path := range paths {
		full := filepath.Join(root, path)
		want := outputs[path]
		if *check {
			actual, e := os.ReadFile(full)
			if e != nil || string(actual) != string(want) {
				stale = append(stale, path)
			}
			continue
		}
		die(os.MkdirAll(filepath.Dir(full), 0755))
		die(os.WriteFile(full, want, 0644))
	}
	if len(stale) > 0 {
		die(fmt.Errorf("stale generated profile contracts: %s", strings.Join(stale, ", ")))
	}
}
