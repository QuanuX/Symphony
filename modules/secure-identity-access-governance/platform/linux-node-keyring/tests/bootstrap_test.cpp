#include <symphony/ssiag/node_keyring_bootstrap.hpp>

#include <algorithm>
#include <array>
#include <chrono>
#include <condition_variable>
#include <cstdlib>
#include <iostream>
#include <mutex>
#include <stdexcept>
#include <string_view>
#include <unistd.h>

namespace boot = symphony::ssiag::node_keyring;
using Status = boot::BootstrapStatus;
using namespace std::chrono_literals;

namespace {
void expect(bool condition, const char* invariant) {
    if (!condition) throw std::runtime_error(invariant);
}
}

// Test executable only. This is invoked by a qualification harness with a
// disposable binding and the expected generated bytes on a pipe.
int main(int argc, char** argv) {
    if (getuid() == 0) return 2;
    if (argc == 4 && std::string_view(argv[1]) == "--expect-refusal") {
        const std::string_view name(argv[2]);
        Status wanted;
        if (name == "binding") wanted = Status::binding_refused;
        else if (name == "missing") wanted = Status::not_found;
        else if (name == "invalid") wanted = Status::invalid;
        else if (name == "unavailable") wanted = Status::unavailable;
        else if (name == "locked") wanted = Status::locked;
        else return 2;
        bool called = false;
        boot::SessionBootstrap selection(argv[3]);
        const auto actual = selection.authenticate(boot::Clock::now() + 5s, {},
            [&](auto, auto, auto) { called = true; return boot::Handshake::refused; });
        return actual == wanted && !called ? 0 : 1;
    }
    if (argc != 2 || isatty(STDIN_FILENO)) return 2;
    std::array<char, 4097> expected{};
    std::cin.read(expected.data(), expected.size());
    const auto length = std::cin.gcount();
    if (!std::cin.eof() || length <= 0 || length > 4096) return 2;
    try {
        expect(setenv("DBUS_SESSION_BUS_ADDRESS", "unix:path=/nonexistent/symphony-fixture", 1) == 0,
               "set unrelated ambient bus");
        unsigned calls = 0;
        const boot::Authenticate login = [&](std::span<const std::byte> value, boot::Clock::time_point until,
                                              std::stop_token stop) {
            ++calls;
            const auto wanted = std::as_bytes(std::span{expected.data(), static_cast<std::size_t>(length)});
            const bool matches = value.size() == wanted.size() && std::equal(value.begin(), value.end(), wanted.begin());
            return !stop.stop_requested() && boot::Clock::now() < until && matches ?
                boot::Handshake::established : boot::Handshake::refused;
        };
        auto deadline = [] { return boot::Clock::now() + 5s; };
        boot::SessionBootstrap attempt(argv[1]);
        expect(attempt.authenticate(deadline(), {}, login) == Status::established, "login with selected generation");
        expect(attempt.authenticate(deadline(), {}, login) == Status::already_attempted, "spent attempt");
        expect(calls == 1, "callback count");

        std::stop_source stop;
        stop.request_stop();
        boot::SessionBootstrap cancelled(argv[1]);
        expect(cancelled.authenticate(deadline(), stop.get_token(), login) == Status::cancelled, "cancel before use");
        boot::SessionBootstrap expired(argv[1]);
        expect(expired.authenticate(boot::Clock::now(), {}, login) == Status::expired, "expired before use");
        boot::SessionBootstrap excessive(argv[1]);
        expect(excessive.authenticate(boot::Clock::now() + 31s, {}, login) == Status::invalid, "lifetime ceiling");
        boot::SessionBootstrap untrusted("/tmp/absent");
        expect(untrusted.authenticate(deadline(), {}, login) == Status::binding_refused, "untrusted binding directory");
        expect(calls == 1, "refused before callback");

        boot::SessionBootstrap interrupted(argv[1]);
        std::stop_source running;
        const auto status = interrupted.authenticate(deadline(), running.get_token(),
            [&](auto, auto, std::stop_token token) {
                running.request_stop();
                expect(token.stop_requested(), "cancellation reaches handshake");
                return boot::Handshake::established;
            });
        expect(status == Status::indeterminate, "interruption after handoff");
        expect(interrupted.authenticate(deadline(), {}, login) == Status::already_attempted, "no retry after handoff");

        boot::SessionBootstrap time_bound(argv[1]);
        bool observed_timeout = false;
        const auto late = time_bound.authenticate(boot::Clock::now() + 2s, {},
            [&](auto, auto until, std::stop_token active) {
                std::mutex m;
                std::condition_variable_any changed;
                std::unique_lock lock(m);
                changed.wait_until(lock, active, until + 2s, [] { return false; });
                observed_timeout = active.stop_requested();
                return boot::Handshake::indeterminate;
            });
        expect(late == Status::indeterminate && observed_timeout, "deadline cancels in-flight handshake");

        boot::SessionBootstrap exception(argv[1]);
        const auto failed = exception.authenticate(deadline(), {},
            [](auto, auto, auto) -> boot::Handshake { throw std::runtime_error("test exception"); });
        expect(failed == Status::indeterminate, "exception after handoff");
        return 0;
    } catch (const std::exception& e) {
        std::cerr << "Qualification failed: " << e.what() << '\n';
        return 1;
    }
}
